const fs = require('fs');
const path = require('path');

const publicDir = path.join(__dirname, 'public');

if (!fs.existsSync(publicDir)) {
  fs.mkdirSync(publicDir, { recursive: true });
}

// Generate build-time env.js if Vercel environment variables exist
const supabaseUrl = process.env.SUPABASE_URL || process.env.NEXT_PUBLIC_SUPABASE_URL || '';
const supabaseAnonKey = process.env.SUPABASE_ANON_KEY || process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY || '';

const envContent = `// Automatically generated by build.js from Vercel environment variables
window.__SKIT_ENV__ = {
  supabaseUrl: ${JSON.stringify(supabaseUrl)},
  supabaseAnonKey: ${JSON.stringify(supabaseAnonKey)},
  configured: ${Boolean(supabaseUrl && supabaseAnonKey)}
};
`;

fs.writeFileSync(path.join(__dirname, 'env.js'), envContent, 'utf8');
fs.writeFileSync(path.join(publicDir, 'env.js'), envContent, 'utf8');

// Files and directories to mirror into public/
const itemsToCopy = [
  'index.html',
  'manifest.json',
  'sw.js',
  'assets',
  'js',
  'env.js',
  'stitch_skit_inventory_design_system'
];

for (const item of itemsToCopy) {
  const src = path.join(__dirname, item);
  const dest = path.join(publicDir, item);

  if (fs.existsSync(src)) {
    fs.cpSync(src, dest, { recursive: true });
    console.log(`Copied ${item} -> public/${item}`);
  }
}

console.log('✅ Static build complete: public/ directory populated successfully.');
